/**
 * Writes data/seed/catalog.sql (loaded by `supabase db reset` via supabase/config.toml).
 * Embeddings are filled later by `pnpm --filter @partspilot/data embed` (needs GEMINI_API_KEY);
 * trigram matching works without them.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { buildCatalog } from "./catalog";

const DATA = fileURLToPath(new URL("..", import.meta.url));
const q = (v: unknown) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const json = (v: unknown) => (v === null || v === undefined ? "null" : `${q(JSON.stringify(v))}::jsonb`);
const arr = (xs: string[]) => `array[${xs.map(q).join(", ")}]::text[]`;

function chunks<T>(xs: T[], n: number): T[][] {
  const out: T[][] = [];
  for (let i = 0; i < xs.length; i += n) out.push(xs.slice(i, i + n));
  return out;
}

const { parts, aliases, references, stats } = buildCatalog();
const sql: string[] = [
  "-- GENERATED by data/scripts/build-seed.ts — do not edit.",
  "-- Catalog data derived from the Fritzing parts library (CC-BY-SA 3.0) and KiCad symbols",
  "-- (CC-BY-SA 4.0); curated profiles CC-BY-SA 4.0. See data/LICENSES.md.",
  "begin;",
];

for (const batch of chunks(parts, 200)) {
  sql.push(
    "insert into public.catalog_parts (id, name, category, manufacturer, source, source_ref, license, buy_query, profile) values",
    batch
      .map((p) => `  (${[q(p.id), q(p.name), q(p.category), q(p.manufacturer), q(p.source), q(p.source_ref), q(p.license), q(p.buy_query), json(p.profile)].join(", ")})`)
      .join(",\n"),
    "on conflict (id) do update set name = excluded.name, category = excluded.category, manufacturer = excluded.manufacturer,",
    "  source = excluded.source, source_ref = excluded.source_ref, license = excluded.license, buy_query = excluded.buy_query,",
    "  profile = excluded.profile, updated_at = now();",
  );
}
for (const batch of chunks(aliases, 500)) {
  sql.push(
    "insert into public.catalog_aliases (part_id, alias) values",
    batch.map((a) => `  (${q(a.part_id)}, ${q(a.alias)})`).join(",\n"),
    "on conflict (part_id, alias) do nothing;",
  );
}
sql.push(
  "insert into public.reference_projects (id, title, goal_examples, plan) values",
  references.map((r) => `  (${q(r.id)}, ${q(r.title)}, ${arr(r.goal_examples)}, ${json(r.plan)})`).join(",\n"),
  "on conflict (id) do update set title = excluded.title, goal_examples = excluded.goal_examples, plan = excluded.plan, updated_at = now();",
  "commit;",
  "",
);

mkdirSync(`${DATA}/seed`, { recursive: true });
writeFileSync(`${DATA}/seed/catalog.sql`, sql.join("\n"));
console.log(
  `seed: ${parts.length} parts (${stats.curated} curated, ${stats.fritzing} fritzing, ${stats.merged} merged into curated, ${stats.skipped} skipped), ${aliases.length} aliases, ${references.length} reference projects`,
);
